function mergeMigrations(tables) {
  const source = read("web/db.js");
  const pairs = new Set(
    [...source.matchAll(/\["([a-z_]+)",\s*"(TEXT|INTEGER|REAL)"\]/g)]
      .map((match) => `${match[1]}:${match[2]}`),
  );
  const documented = new Set(
    Object.values(EXTRA_COLUMNS).flat().map(([name, type]) => `${name}:${type}`),
  );
  const undocumented = [...pairs].filter((pair) => !documented.has(pair)).sort();
  const missing = [...documented].filter((pair) => !pairs.has(pair)).sort();
  if (undocumented.length) {
    fail(`new migrated column without a schema note: ${undocumented.join(", ")}. Add it to EXTRA_COLUMNS`);
  }
  if (missing.length) {
    fail(`schema note for a column the code no longer adds: ${missing.join(", ")}. Remove it from EXTRA_COLUMNS`);
  }

  for (const [table, extras] of Object.entries(EXTRA_COLUMNS)) {
    const target = tables.find((entry) => entry.name === table);
    if (!target) fail(`migration columns name missing table ${table}`);
    for (const [name, rawType] of extras) {
      if (target.columns.some((column) => column.name === name)) continue;
      target.columns.push({
        name,
        type: { TEXT: "text", INTEGER: "integer", REAL: "real" }[rawType],
        key: "",
      });
    }
  }
}

const SCHEMA_GROUPS = {
  "schema-ledger": ["account", "fact", "import_run", "issue"],
  "schema-assets": ["account", "holding", "locker", "setting"],
};

const SHOW_COLUMNS = new Set([
  "txn_date", "amount_paise", "balance_paise", "category", "value_paise",
  "file", "rows_read", "rows_kept", "kind", "state", "quantity",
  "cost_paise", "rent_paise", "number", "value",
]);

function schemaDiagram(tables, group) {
  const names = new Set(group.map((name) => name.toUpperCase()));
  const edges = [];
  for (const table of tables.filter((entry) => group.includes(entry.name))) {
    for (const column of table.columns) {
      if (!column.name.endsWith("_id")) continue;
      const key = `${table.name}.${column.name}`;
      if (EXTERNAL_IDS.has(key)) continue;
      const relation = RELATIONS[key];
      if (!relation) fail(`new foreign key ${key} has no relation note; add it to RELATIONS`);
      const [parent, verb] = relation;
      if (!names.has(parent)) continue;
      edges.push(`${parent} ||--o{ ${table.name.toUpperCase()} : ${verb}`);
    }
  }
  edges.sort();

  const entities = tables.filter((table) => group.includes(table.name)).map((table) => {
    const shown = table.columns.filter((column) => column.key
      || column.name.endsWith("_id") || SHOW_COLUMNS.has(column.name));
    const rows = shown.map((column) => {
      const suffix = column.key ? ` ${column.key}` : "";
      return `    ${column.type} ${column.name}${suffix}`;
    });
    return `  ${table.name.toUpperCase()} {\n${rows.join("\n")}\n  }`;
  });

  return `erDiagram\n${edges.map((edge) => `  ${edge}`).join("\n")}\n\n${entities.join("\n\n")}`;
}

function checkSchemaGroups(tables) {
  const grouped = new Set(Object.values(SCHEMA_GROUPS).flat());
  const ungrouped = tables.map((table) => table.name).filter((name) => !grouped.has(name));
  const missing = [...grouped].filter((name) => !tables.some((table) => table.name === name));
  if (ungrouped.length) {
    fail(`new table without a schema group: ${ungrouped.join(", ")}. Add it to SCHEMA_GROUPS`);
  }
  if (missing.length) {
    fail(`schema group names a table the code no longer creates: ${missing.join(", ")}`);
  }
}

