const MODULES = {
  "db.js": ["data", "SQLite store"],
  "ledger.js": ["data", "reconciliation rules"],
  "dbatrest.js": ["crypto", "seal the database"],
  "crypto.js": ["crypto", "AES-GCM and PBKDF2"],
  "vault.js": ["crypto", "key envelope"],
  "backup.js": ["backup", "manual snapshots"],
  "blockbackup.js": ["backup", "64 KiB automatic copy"],
  "autobackup.js": ["backup", "automatic schedule"],
  "storage.js": ["io", "storage adapter"],
  "drive.js": ["io", "Google Drive API"],
};

function importsOf(file) {
  const source = read(`web/${file}`);
  const found = new Set();
  for (const match of source.matchAll(/import\s+\{[^}]*\}\s+from\s+"\.\/([\w.-]+\.js)"/g)) {
    found.add(match[1]);
  }
  for (const match of source.matchAll(/import\s+[\w$]+\s+from\s+"\.\/([\w.-]+\.js)"/g)) {
    found.add(match[1]);
  }
  return [...found];
}

function moduleDiagram() {
  const names = new Set(Object.keys(MODULES));
  const edges = [];
  for (const file of Object.keys(MODULES)) {
    if (!existsSync(join(ROOT, "web", file))) fail(`module map names missing web/${file}`);
    const imported = importsOf(file);
    const unknown = imported.filter((target) => !names.has(target));
    if (unknown.length) {
      fail(`core module ${file} imports ${unknown.join(", ")} outside MODULES. Add it to the map or explain why it is omitted`);
    }
    for (const target of imported) {
      edges.push(`  ${file.replace(/\.js$/, "")}["${file}<br/>${MODULES[file][1]}"] --> ${target.replace(/\.js$/, "")}["${target}<br/>${MODULES[target][1]}"]`);
    }
  }
  edges.sort();

  const classes = { data: [], crypto: [], backup: [], io: [] };
  for (const [file, [layer]] of Object.entries(MODULES)) classes[layer].push(file.replace(/\.js$/, ""));
  const classLines = Object.entries(classes)
    .filter(([, members]) => members.length)
    .map(([layer, members]) => `  class ${members.join(",")} ${layer}`);

  return [
    "flowchart LR",
    ...edges,
    "",
    ...classLines,
    "  classDef data fill:#e2efec,stroke:#24837b,color:#100f0f,stroke-width:1.5px",
    "  classDef crypto fill:#f7e6cc,stroke:#a35a00,color:#100f0f,stroke-width:1.5px",
    "  classDef backup fill:#e8f0f8,stroke:#205ea6,color:#100f0f,stroke-width:1.5px",
    "  classDef io fill:#efe9f7,stroke:#6b4ea3,color:#100f0f,stroke-width:1.5px",
  ].join("\n");
}

