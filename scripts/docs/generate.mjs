const ROUTES = {
  "server:/__health": ["GET", "Local Node server", "Health probe used by `launch.sh`."],
  "server:/__market/debt": ["GET", "Local Node server", "BSE debt bhavcopy prices, cached per ISIN and per day."],
  "server:/__market/bond": ["GET", "Local Node server", "SMEST bond terms plus a BSE quote, each cached separately."],
  "server:/<file>": ["GET", "Local Node server", "Static app. Refuses dotfiles, `/private` and its own source."],
  "worker:/": ["GET", "OAuth Worker", "Redirects a human to `APP_RETURN`."],
  "worker:/health": ["GET", "OAuth Worker", "Liveness JSON."],
  "worker:/oauth/start": ["GET", "OAuth Worker", "Creates PKCE and state, seals them in a cookie, redirects to Google."],
  "worker:/oauth/callback": ["GET", "OAuth Worker", "Checks state, exchanges the code, seals the refresh token."],
  "worker:/token": ["POST", "OAuth Worker", "Refreshes and returns a short-lived access token."],
  "worker:/disconnect": ["POST", "OAuth Worker", "Revokes the grant and clears the cookie."],
  "pages:/token": ["POST", "Pages worker", "Same broker on the app origin, so the cookie is first-party."],
  "pages:/disconnect": ["POST", "Pages worker", "Same disconnect route on the app origin."],
  "pages:/health": ["GET", "Pages worker", "Same liveness route on the app origin."],
  "pages:/oauth/*": ["GET", "Pages worker", "Broker consent and callback routes on the app origin."],
  "pages:/__market/*": ["GET", "Pages worker", "JSON 501: a static host cannot reach an exchange feed."],
  "pages:/<file>": ["GET", "Pages worker", "Serves the static app and adds security headers."],
};

function routesTable() {
  const server = read("web/server.mjs");
  const worker = read("worker/src/index.js");
  const pages = read("scripts/pages/_worker.js");

  const keys = new Set(["server:/<file>", "pages:/<file>"]);
  for (const match of server.matchAll(/url\.pathname === "([^"]+)"/g)) keys.add(`server:${match[1]}`);
  for (const match of worker.matchAll(/case "([^"]+)":/g)) keys.add(`worker:${match[1]}`);

  const api = pages.match(/const API = new Set\(\[([\s\S]*?)\]\)/);
  if (!api) fail("scripts/pages/_worker.js has no API route set");
  for (const match of api[1].matchAll(/"([^"]+)"/g)) keys.add(`pages:${match[1]}`);
  for (const match of pages.matchAll(/startsWith\("([^"]+)"\)/g)) keys.add(`pages:${match[1]}*`);

  const known = new Set(Object.keys(ROUTES));
  const missing = [...keys].filter((key) => !known.has(key)).sort();
  const removed = [...known].filter((key) => !keys.has(key)).sort();
  if (missing.length) fail(`new route without a note: ${missing.join(", ")}. Add it to ROUTES in scripts/docs/generate.mjs`);
  if (removed.length) fail(`documented route no longer in source: ${removed.join(", ")}. Remove it from ROUTES`);

  const rows = [...keys].sort().map((key) => {
    const [method, where, note] = ROUTES[key];
    const [place, path] = key.split(":");
    return `| ${method} | \`${path}\` | ${where} | ${note} |`;
  });

  return [
    MARK,
    "",
    "# HTTP routes",
    "",
    "Every route the code registers. Generated from the route switches, so a new route",
    "fails the docs check until it is described here.",
    "",
    "| Method | Path | Runs where | What it does |",
    "|---|---|---|---|",
    ...rows,
  ].join("\n");
}

// --- facts -----------------------------------------------------------------

function facts(tables, webTests, workerTests) {
  return [
    MARK,
    "",
    "# Project facts",
    "",
    "Counts that would otherwise go stale in prose. Generated from the code and from",
    "the test runs, never typed by hand.",
    "",
    "| Fact | Value |",
    "|---|---|",
    `| Web test suite | ${webTests.tests} tests, ${webTests.pass} passing |`,
    `| Worker test suite | ${workerTests.tests} tests, ${workerTests.pass} passing |`,
    `| SQLite tables | ${tables.length} (${tables.map((table) => `\`${table.name}\``).join(", ")}) |`,
    `| Core modules in the import map | ${Object.keys(MODULES).length} |`,
    `| HTTP routes documented | ${Object.keys(ROUTES).length} |`,
    "| Vendored browser libraries | sql.js, SheetJS, pdf.js |",
  ].join("\n");
}

// --- main ------------------------------------------------------------------

const tables = parseSchema();
mergeMigrations(tables);
checkSchemaGroups(tables);
for (const [name, group] of Object.entries(SCHEMA_GROUPS)) {
  put(`docs/diagrams/${name}.mmd`, schemaDiagram(tables, group));
}
put("docs/diagrams/modules.mmd", moduleDiagram());
put("docs/generated/routes.md", routesTable());

const webTests = runSuite("web", "web");
const workerTests = runSuite("worker", "worker");
put("docs/generated/facts.md", facts(tables, webTests, workerTests));

const paths = [...outputs.keys()].sort();
if (CHECK) {
  const stale = paths.filter((path) => {
    const file = join(ROOT, path);
    return !existsSync(file) || readFileSync(file, "utf8") !== outputs.get(path);
  });
  if (stale.length) {
    fail(`generated docs are stale:\n  ${stale.join("\n  ")}\nRun node scripts/docs/generate.mjs --write and commit the result.`);
  }
  console.log(`docs: ${paths.length} generated files current`);
} else {
  for (const path of paths) {
    const file = join(ROOT, path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, outputs.get(path));
  }
  console.log(`docs: wrote ${paths.length} generated files`);
}
